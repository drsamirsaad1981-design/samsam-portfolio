"""🥇 Gold / 🥈 Silver as portfolio assets: added in grams and $ per gram, kept in troy ounces (priced like PAXG / KAG),
shown in grams, under Precious Metals, always Hold, not in the altcoins total, with CMC / Prediction / Liq.Map links."""
import sys, pathlib
from playwright.sync_api import sync_playwright
sys.path.insert(0, str(pathlib.Path(__file__).parent)); import e2e_setup as S
res = []; SH = pathlib.Path(__file__).parent / 'shots'
GPO = 31.1034768
def check(n, c, d=''): res.append(bool(c)); print(('PASS ' if c else 'FAIL ') + n + ('' if c else f' -> {d}'), flush=True)
with sync_playwright() as p:
    br = p.chromium.launch()
    ctx = br.new_context(viewport={'width': 390, 'height': 844}, is_mobile=True, has_touch=True, device_scale_factor=2); S.setup(ctx); errs = []
    pg = ctx.new_page(); pg.on('pageerror', lambda e: errs.append(str(e)))
    pg.goto(S.SITE + '/index.html'); pg.click('#samsamSignInBtn'); S.wait_ready(pg); pg.wait_for_timeout(1200)

    pg.evaluate("openAddCoin()"); pg.wait_for_timeout(200)
    check('Add Coin has the 🥇 Gold / 🥈 Silver shortcuts', pg.locator('.ac-metals button').count() == 2)
    pg.click('.ac-metals button >> nth=0'); pg.wait_for_timeout(300)
    f = pg.evaluate("[acSym.value, acCgId.value, acCmc.value, acCat.value, acQtyLbl.textContent, acPriceLbl.textContent]")
    check('Gold shortcut: XAU, pax-gold, Precious Metals', f[:4] == ['XAU', 'pax-gold', 'pax-gold', 'metals'], f)
    check('labels ask for grams and price per gram', 'grams' in f[4] and 'per gram' in f[5], f)
    check('metal box shown, network row hidden, weight chips there', pg.evaluate("[acMetalBox.hidden, acNetRow.hidden, document.querySelectorAll('#acChips button').length]") == [False, True, 9])
    pg.fill('#acQty', '100'); pg.fill('#acPrice', '80'); pg.fill('#acDate', '2025-06-02'); pg.select_option('#acVault', 'home')
    pg.screenshot(path=str(SH / 'metals-add.png'))
    pg.evaluate("applyAddCoin()"); pg.wait_for_timeout(900)
    c = pg.evaluate("(() => { const c = Samsam.getState().portfolio.find(x => x.sym === 'XAU'); return c && [c.qty, c.basePrice, c.cat, c.cgId]; })()")
    check('stored in troy ounces: 100 g → 3.215 oz', c and abs(c[0] - 100 / GPO) < 1e-9, c)
    check('Avg. Buy Price stored per ounce: $80/g → $2,488.28/oz', c and abs(c[1] - 80 * GPO) < 1e-6, c)
    check('category metals, priced as pax-gold', c and c[2] == 'metals' and c[3] == 'pax-gold', c)
    tx0 = pg.evaluate("Samsam.getState().transactions.filter(t => t.sym === 'XAU')[0].date")
    check('buy date you picked is kept (2 Jun 2025)', tx0.startswith('2025-06-02'), tx0)
    check('where kept: 🏠 home', pg.evaluate("Samsam.getState().coins.find(c => c.sym === 'XAU').vault") == 'home')

    # Buy more: 50 g at $90/g
    pg.evaluate("openAddTx('buy','XAU')"); pg.wait_for_timeout(300)
    bo = pg.evaluate("[addCoinModal.classList.contains('show'), atxBackdrop.classList.contains('show'), acTitle.textContent, acSym.value, acNetRow.offsetParent === null, acVault.value]")
    check('+ Buy on gold opens the same Add window (Buy Gold), no network row, keeps where kept', bo[0] and not bo[1] and 'Buy Gold' in bo[2] and bo[3] == 'XAU' and bo[4] and bo[5] == 'home', bo)
    pg.fill('#acQty', '50'); pg.fill('#acPrice', '90'); pg.wait_for_timeout(100)
    pg.evaluate("applyAddCoin()"); pg.wait_for_timeout(900)
    pg.evaluate("openAddTx('sell','XAU')"); pg.wait_for_timeout(200)
    so = pg.evaluate("[atxCoin.textContent, getComputedStyle(atxNetFeeRow).display, atxQtyLabel.textContent]")
    check('Sell form: holding in grams, no network fee', '150 g' in so[0] and so[1] == 'none' and 'grams' in so[2], so)
    pg.fill('#atxQty', '10'); pg.fill('#atxPrice', '100'); pg.wait_for_timeout(100)
    pv = pg.inner_text('#atxPreview')
    check('sell preview: holdings after in grams (140 g)', '140 g' in pv and '/g' in pv, pv)
    pg.evaluate("closeAddTx()")
    c = pg.evaluate("(() => { const c = Samsam.getState().portfolio.find(x => x.sym === 'XAU'); return [c.qty, c.basePrice]; })()")
    check('after buy: 150 g', abs(c[0] * GPO - 150) < 1e-6, c)
    check('after buy: avg $83.33/g', abs(c[1] / GPO - (100 * 80 + 50 * 90) / 150) < 1e-6, c)

    # edit that buy: shown back in grams / $ per gram
    tid = pg.evaluate("Samsam.getState().transactions.filter(t => t.sym === 'XAU' && t.type === 'buy').slice(-1)[0].id")
    pg.evaluate(f"openEditTx('{tid}')"); pg.wait_for_timeout(200)
    ev = pg.evaluate("[+atxQty.value, +atxPrice.value]")
    check('edit shows 50 g at $90/g', abs(ev[0] - 50) < 1e-4 and abs(ev[1] - 90) < 1e-4, ev)
    pg.evaluate("closeAddTx()")

    # how it shows
    pg.wait_for_timeout(500)
    sig = pg.evaluate("getAction('XAU', -50, portfolio.find(c => c.sym === 'XAU'))")
    check('Signal is always Hold (even 50% down)', sig == 'hold', sig)
    hc = pg.evaluate("SamsamCoins.holdCell('XAU', 1000, portfolio.find(c => c.sym === 'XAU').qty)")
    check('holdings shown in grams', '150 g' in hc, hc)
    av = pg.evaluate("avgShown(portfolio.find(c => c.sym === 'XAU'))")
    check('Avg. Buy Price shown per gram', av.endswith('/g') and '83.3' in av, av)
    tt = pg.evaluate("(() => { const s = calcStats(); return [s.total, portfolio.reduce((a, c) => a + c.qty * (c.sym === 'BTC' ? btcPrice : c.currentPrice), 0), s.metalTotal]; })()")
    check('Total Portfolio includes the gold (metals not with altcoins, but in the total)', abs(tt[0] - tt[1]) < 1e-6 and tt[2] > 0, tt)
    z = pg.evaluate("SamsamCoins.zakat('XAU', Samsam.getState())")
    check('zakat: 150 g ≥ 85 g nisab, held since Jun 2025 → due, 3.75 g', z and z['due'] and abs(z['zakatG'] - 3.75) < 1e-6, z)
    hide0 = pg.evaluate("metalsCard.hidden")
    order = pg.evaluate("[!!(document.getElementById('btcTicker').compareDocumentPosition(metalsCard) & Node.DOCUMENT_POSITION_FOLLOWING), document.querySelector('.header-stats').contains(metalsCard)]")
    check('Overview: the moving line stays right under the four cards, metals card after it', order == [True, False], order)
    ov = pg.inner_text('#metalsSub')
    check('Overview metals row: 🏠 Home safe and zakat due', 'Home safe' in ov and 'Zakat due' in ov, ov)
    pg.click('#metalsSub .mt-row'); pg.wait_for_timeout(900)
    hh = pg.evaluate("[document.getElementById('htxHoldings24').textContent, document.getElementById('htxNet').textContent]")
    check('tap the row → its History, amounts in grams, where kept + zakat', '150 g' in hh[0] and 'Home safe' in hh[1] and 'Zakat due' in hh[1], hh)
    rows = pg.evaluate("[...document.querySelectorAll('.htx-row-qty')].map(e => e.textContent)")
    check('History rows in grams (+100 g, +50 g)', '+100 g' in rows and '+50 g' in rows, rows)
    pg.click('#htxNet'); pg.wait_for_timeout(300)
    pg.click('#vaultList button:nth-child(2)'); pg.click('#vaultSave'); pg.wait_for_timeout(700)
    check('change where kept → 🏦 bank', pg.evaluate("Samsam.getState().coins.find(c => c.sym === 'XAU').vault") == 'bank')
    pg.keyboard.press('Escape'); pg.goto(S.SITE + '/index.html'); S.wait_ready(pg); pg.wait_for_timeout(1200)
    mt = pg.evaluate("[metalsCard.hidden, metalsSub.textContent, document.querySelector('#metalsCard .mt-open').getAttribute('href')]")
    check('Overview: 🥇 Precious Metals card shows 150 g of gold and opens the Metals page', mt[0] is False and all(x in mt[1].replace('\u2066','').replace('\u2069','') for x in ('Gold', '150 g', 'Bought $83.33/g', 'Cost', 'Profit')) and mt[2].endswith('#metals'), mt)
    pg.locator('#metalsCard').scroll_into_view_if_needed(); pg.screenshot(path=str(SH / 'metals-overview.png'))
    pg.set_viewport_size({'width': 1400, 'height': 900}); pg.wait_for_timeout(400); pg.locator('#metalsCard').scroll_into_view_if_needed(); pg.screenshot(path=str(SH / 'metals-overview-desktop.png')); pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(300)
    ql = pg.evaluate("SamsamCoins.quickLinks('XAU')")
    check('links: CoinGlass XAUT map, CoinCodex pax-gold, CMC pax-gold',
          'coin=XAUT' in ql and 'pax-gold' in ql and 'coinmarketcap.com/currencies/pax-gold' in ql and 'Try Liq' not in ql, ql)
    qs = pg.evaluate("SamsamCoins.quickLinks('XAG')")
    check('silver: Liq.Map marked "Try" (CoinGlass may have none)', 'Try Liq.Map' in qs and 'kinesis-silver' in qs, qs)
    check('Precious Metals category exists', pg.evaluate("SamsamTaxonomy.label ? SamsamTaxonomy.label('metals') : JSON.stringify(SamsamTaxonomy)").find('Precious Metals') >= 0)

    # silver shortcut: digital, in tokens, invoice total
    pg.evaluate("openAddCoin()"); pg.click('.ac-metals button >> nth=1'); pg.wait_for_timeout(200)
    check('Silver shortcut: XAG, kinesis-silver', pg.evaluate("[acSym.value, acCgId.value]") == ['XAG', 'kinesis-silver'])
    pg.select_option('#acVault', 'digital'); pg.wait_for_timeout(100)
    check('📱 digital → amount in tokens', 'tokens' in pg.inner_text('#acQtyLbl'))
    pg.evaluate("acSetPm('total')"); pg.fill('#acQty', '10'); pg.fill('#acPrice', '400'); pg.wait_for_timeout(100)
    pv = pg.inner_text('#acPreview')
    check('preview: 10 tokens = 311.03 g, $1.29/g', '311.035 g' in pv and '/g' in pv, pv)
    pg.evaluate("applyAddCoin()"); pg.wait_for_timeout(900)
    sv = pg.evaluate("(() => { const c = Samsam.getState().portfolio.find(x => x.sym === 'XAG'); return c && [c.qty, c.basePrice]; })()")
    check('silver stored: 10 oz at $40/oz', sv and abs(sv[0] - 10) < 1e-9 and abs(sv[1] - 40) < 1e-9, sv)
    zs = pg.evaluate("SamsamCoins.zakat('XAG', Samsam.getState())")
    check('zakat silver: 311 g < 595 g nisab → none', zs and not zs['meets'], zs)
    pg.evaluate("Samsam.removeCoin('XAG')"); pg.wait_for_timeout(600)

    # Market Hub → Metals: your metals on top
    pg.goto(S.SITE + '/market.html#metals'); S.wait_ready(pg); pg.wait_for_timeout(2500)
    mine = pg.locator('#vMetals .as-mine')
    t = mine.inner_text() if mine.count() else ''
    check('Metals tab: "Your metals" card with 150 g of gold', 'Your metals' in t and '150' in t and 'Gold 24k' in t, t)
    check('…with the gram price vs your average and the add buttons', '/' not in '' and 'your avg' in t and mine.locator('[data-add]').count() == 2, t)
    pg.screenshot(path=str(SH / 'metals-mine.png'), full_page=False)
    pg.set_viewport_size({'width': 1400, 'height': 900}); pg.wait_for_timeout(400); pg.screenshot(path=str(SH / 'metals-mine-desktop.png')); pg.set_viewport_size({'width': 390, 'height': 844}); pg.wait_for_timeout(300)
    pg.click('#vMetals [data-add="XAG"]'); pg.wait_for_timeout(300)
    check('Add silver from the Metals tab opens Add Coin on XAG', pg.evaluate("[addCoinModal.classList.contains('show') || getComputedStyle(addCoinModal).display !== 'none', acSym.value]") == [True, 'XAG'])
    pg.evaluate("closeAddCoin()")
    pg.evaluate("Samsam.removeCoin('XAU')"); pg.wait_for_timeout(900)
    t2 = pg.inner_text('#vMetals .as-mine') if pg.locator('#vMetals .as-mine').count() else ''
    check('no metals held → the card invites you to add gold / silver', 'Add gold' in t2 and 'Add silver' in t2, t2)
    pg.goto(S.SITE + '/index.html'); S.wait_ready(pg); pg.wait_for_timeout(1200)
    check('Overview: no metals → no metals card', pg.evaluate("metalsCard.hidden") is True)
    check('no page errors', not errs, errs)
    br.close()
print(f'metals_test: {sum(res)}/{len(res)} passed')
